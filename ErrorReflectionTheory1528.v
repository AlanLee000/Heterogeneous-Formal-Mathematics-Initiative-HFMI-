(** Sections 0--2: finite sequences and the comparison-dimension algebra. *)

Definition nonempty {A : Type} (xs : list A) : Prop := xs <> [].

Fixpoint adjacent {A : Type} (R : A -> A -> Prop) (xs : list A) : Prop :=
  match xs with
  | [] => True
  | x :: xs' =>
      match xs' with
      | [] => True
      | y :: _ => R x y /\ adjacent R xs'
      end
  end.

Inductive DimTerm (AtomDim : Type) : Type :=
| DAtom : AtomDim -> DimTerm AtomDim
| DTensor : DimTerm AtomDim -> DimTerm AtomDim -> DimTerm AtomDim
| DOption : DimTerm AtomDim -> DimTerm AtomDim -> DimTerm AtomDim
| DSeq : DimTerm AtomDim -> DimTerm AtomDim -> DimTerm AtomDim.

Arguments DAtom {AtomDim} _.
Arguments DTensor {AtomDim} _ _.
Arguments DOption {AtomDim} _ _.
Arguments DSeq {AtomDim} _ _.

(** The least equivalence relation containing [Theta] and closed under all
    three constructors. This is the setoid presentation of DimTerm/Theta. *)
Inductive dim_congruence {AtomDim : Type}
    (Theta : DimTerm AtomDim -> DimTerm AtomDim -> Prop)
    : DimTerm AtomDim -> DimTerm AtomDim -> Prop :=
| DC_refl : forall x, dim_congruence Theta x x
| DC_theta : forall x y, Theta x y -> dim_congruence Theta x y
| DC_sym : forall x y,
    dim_congruence Theta x y -> dim_congruence Theta y x
| DC_trans : forall x y z,
    dim_congruence Theta x y ->
    dim_congruence Theta y z ->
    dim_congruence Theta x z
| DC_tensor : forall x x' y y',
    dim_congruence Theta x x' ->
    dim_congruence Theta y y' ->
    dim_congruence Theta (DTensor x y) (DTensor x' y')
| DC_option : forall x x' y y',
    dim_congruence Theta x x' ->
    dim_congruence Theta y y' ->
    dim_congruence Theta (DOption x y) (DOption x' y')
| DC_seq : forall x x' y y',
    dim_congruence Theta x x' ->
    dim_congruence Theta y y' ->
    dim_congruence Theta (DSeq x y) (DSeq x' y').

Lemma dim_tensor_well_defined :
  forall (AtomDim : Type)
         (Theta : DimTerm AtomDim -> DimTerm AtomDim -> Prop)
         x x' y y',
    dim_congruence Theta x x' ->
    dim_congruence Theta y y' ->
    dim_congruence Theta (DTensor x y) (DTensor x' y').
Proof.
  intros AtomDim Theta x x' y y' Hx Hy.
  exact (DC_tensor Hx Hy).
Qed.

Lemma dim_option_well_defined :
  forall (AtomDim : Type)
         (Theta : DimTerm AtomDim -> DimTerm AtomDim -> Prop)
         x x' y y',
    dim_congruence Theta x x' ->
    dim_congruence Theta y y' ->
    dim_congruence Theta (DOption x y) (DOption x' y').
Proof.
  intros AtomDim Theta x x' y y' Hx Hy.
  exact (DC_option Hx Hy).
Qed.

Lemma dim_seq_well_defined :
  forall (AtomDim : Type)
         (Theta : DimTerm AtomDim -> DimTerm AtomDim -> Prop)
         x x' y y',
    dim_congruence Theta x x' ->
    dim_congruence Theta y y' ->
    dim_congruence Theta (DSeq x y) (DSeq x' y').
Proof.
  intros AtomDim Theta x x' y y' Hx Hy.
  exact (DC_seq Hx Hy).
Qed.

Record AtomicDimensionBasis : Type := {
  AtomDim : Type;
  a_bind : AtomDim;
  a_rule : AtomDim;
  a_model : AtomDim;
  a_truth : AtomDim;
  a_boundary : AtomDim;
  five_atoms_distinct :
    NoDup [a_bind; a_rule; a_model; a_truth; a_boundary]
}.

Definition Bind (D : AtomicDimensionBasis) : DimTerm (AtomDim D) :=
  DAtom (a_bind D).
Definition RuleDim (D : AtomicDimensionBasis) : DimTerm (AtomDim D) :=
  DAtom (a_rule D).
Definition ModelDim (D : AtomicDimensionBasis) : DimTerm (AtomDim D) :=
  DAtom (a_model D).
Definition TruthDim (D : AtomicDimensionBasis) : DimTerm (AtomDim D) :=
  DAtom (a_truth D).
Definition BoundaryDim (D : AtomicDimensionBasis) : DimTerm (AtomDim D) :=
  DAtom (a_boundary D).

(** Sections 1 and 3: the bottom environment and the ten-component
    comparison-reflective error calculus. *)

Record BottomEnvironment : Type := {
  Correct : Type;
  Error : Type;
  Rule : Type;
  Boundary : Type;
  correct_step : Correct -> Correct -> Prop;
  ordinary_error_step : Error -> Error -> Prop
}.

Record ComparisonCalculus : Type := {
  base : BottomEnvironment;

  (** A comparison calculus does not receive an arbitrary dimension carrier.
      Its dimensions are exactly the terms of the explicitly presented
      algebra, read modulo the least congruence generated by [dimension_equations].
      Rocq has no native quotient type, so equality in the quotient is carried
      by [dim_congruence] below and every relation is required to respect it. *)
  dimension_basis : AtomicDimensionBasis;
  dimension_equations :
    DimTerm (AtomDim dimension_basis) ->
    DimTerm (AtomDim dimension_basis) -> Prop;

  Witness : Type;
  Diff : DimTerm (AtomDim dimension_basis) ->
         Correct base -> Error base -> Witness -> Prop;
  Next : DimTerm (AtomDim dimension_basis) -> Correct base -> Error base ->
         Correct base -> Error base -> Prop;
  InvDelta : DimTerm (AtomDim dimension_basis) ->
             Correct base -> Error base -> Witness -> Prop;
  InvBack : DimTerm (AtomDim dimension_basis) ->
            Correct base -> Error base -> Witness ->
            Boundary base -> Rule base -> Prop;
  PresDelta : DimTerm (AtomDim dimension_basis) ->
              DimTerm (AtomDim dimension_basis) ->
              Correct base -> Error base -> Witness ->
              Correct base -> Error base -> Witness -> Prop;
  PresBack : DimTerm (AtomDim dimension_basis) ->
             DimTerm (AtomDim dimension_basis) ->
             Correct base -> Error base -> Witness ->
             Boundary base -> Rule base ->
             Correct base -> Error base -> Witness ->
             Boundary base -> Rule base -> Prop;
  Back : DimTerm (AtomDim dimension_basis) ->
         Correct base -> Error base -> Boundary base -> Rule base -> Prop;

  diff_respects_dimension : forall k k' c e w,
    dim_congruence dimension_equations k k' ->
    (Diff k c e w <-> Diff k' c e w);
  next_respects_dimension : forall k k' c e c' e',
    dim_congruence dimension_equations k k' ->
    (Next k c e c' e' <-> Next k' c e c' e');
  inv_delta_respects_dimension : forall k k' c e w,
    dim_congruence dimension_equations k k' ->
    (InvDelta k c e w <-> InvDelta k' c e w);
  inv_back_respects_dimension : forall k k' c e w b r,
    dim_congruence dimension_equations k k' ->
    (InvBack k c e w b r <-> InvBack k' c e w b r);
  pres_delta_respects_dimensions : forall k k' l l' c e w c' e' w',
    dim_congruence dimension_equations k k' ->
    dim_congruence dimension_equations l l' ->
    (PresDelta k l c e w c' e' w' <->
     PresDelta k' l' c e w c' e' w');
  pres_back_respects_dimensions :
    forall k k' l l' c e w b r c' e' w' b' r',
    dim_congruence dimension_equations k k' ->
    dim_congruence dimension_equations l l' ->
    (PresBack k l c e w b r c' e' w' b' r' <->
     PresBack k' l' c e w b r c' e' w' b' r');
  back_respects_dimension : forall k k' c e b r,
    dim_congruence dimension_equations k k' ->
    (Back k c e b r <-> Back k' c e b r)
}.

Definition Dimension (A : ComparisonCalculus) : Type :=
  DimTerm (AtomDim (dimension_basis A)).

Definition dimension_equiv (A : ComparisonCalculus)
    : Dimension A -> Dimension A -> Prop :=
  dim_congruence (dimension_equations A).

Arguments dimension_equiv A _ _ : clear implicits.

Definition dim_tensor (A : ComparisonCalculus)
