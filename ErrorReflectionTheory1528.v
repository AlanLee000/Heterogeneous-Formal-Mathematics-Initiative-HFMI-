Lemma forall_nth_error :
  forall (T : Type) (P : T -> Prop) xs i x,
    Forall P xs ->
    nth_error xs i = Some x ->
    P x.
Proof.
  intros T P xs i x Hall Hnth.
  rewrite Forall_forall in Hall.
  apply Hall.
  eapply nth_error_In.
  exact Hnth.
Qed.

Lemma adjacent_nth_error :
  forall (T : Type) (R : T -> T -> Prop) xs i x y,
    adjacent R xs ->
    nth_error xs i = Some x ->
    nth_error xs (S i) = Some y ->
    R x y.
Proof.
  intros T R xs.
  induction xs as [| a xs IH].
  - intros i x y Hadj Hx.
    destruct i; discriminate.
  - intros i x y Hadj Hx Hy.
    destruct xs as [| b tail].
    + destruct i; discriminate.
    + destruct Hadj as [Hab Htail].
      destruct i as [| i].
      * simpl in Hx, Hy.
        inversion Hx; inversion Hy; subst.
        exact Hab.
      * simpl in Hx, Hy.
        eapply IH.
        -- exact Htail.
        -- exact Hx.
        -- exact Hy.
Qed.

