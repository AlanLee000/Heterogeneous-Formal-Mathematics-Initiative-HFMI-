Definition step_C2 (c c' : C2) : Prop :=
  match c, c' with
  | C0, C1 => True
  | _, _ => False
  end.

Definition sigma_map (s : list E2) : option (list C2) :=
  match s with
  | [E0] => Some [C0]
  | [E0; E1] => Some [C0; C1]
  | _ => None
  end.

Lemma sigma_map_cases :
  forall s cs,
    sigma_map s = Some cs ->
    (s = [E0] /\ cs = [C0]) \/
    (s = [E0; E1] /\ cs = [C0; C1]).
Proof.
  intros s cs H.
  destruct s as [| e s'].
  - discriminate.
  - destruct e.
    + destruct s' as [| e' s''].
      * left.
        inversion H.
        split; reflexivity.
      * destruct e'.
        -- discriminate.
        -- destruct s'' as [| e'' tail].
           ++ right.
              inversion H.
              split; reflexivity.
           ++ discriminate.
    + discriminate.
Qed.

Lemma sigma_map_nonempty :
  forall s cs, sigma_map s = Some cs -> s <> [].
Proof.
  intros s cs H.
  destruct (sigma_map_cases s H) as [[Hs _] | [Hs _]];
    subst s; discriminate.
Qed.

Lemma sigma_map_length :
  forall s cs, sigma_map s = Some cs -> length cs = length s.
Proof.
  intros s cs H.
  destruct (sigma_map_cases s H) as [[Hs Hcs] | [Hs Hcs]];
    subst s; subst cs; reflexivity.
Qed.

Lemma sigma_map_correct :
  forall s cs, sigma_map s = Some cs ->
    adjacent step_C2 cs.
Proof.
  intros s cs H.
  destruct (sigma_map_cases s H) as [[Hs Hcs] | [Hs Hcs]];
    subst s; subst cs; simpl; repeat split; exact I.
Qed.

Lemma sigma_map_prefix_closed :
  forall s cs m,
    sigma_map s = Some cs ->
    1 <= m <= length s ->
    exists cs', sigma_map (firstn m s) = Some cs'.
Proof.
  intros s cs m H Hm.
  destruct (sigma_map_cases s H) as [[Hs Hcs] | [Hs Hcs]].
  - subst s.
    assert (m = 1) by (simpl in Hm; lia).
    subst m.
    exists [C0].
    reflexivity.
  - subst s.
    assert (m = 1 \/ m = 2) by (simpl in Hm; lia).
    destruct H0 as [Hm1 | Hm2].
    + subst m.
      exists [C0].
      reflexivity.
    + subst m.
      exists [C0; C1].
      reflexivity.
Qed.

Lemma sigma_map_prefix_compatible :
  forall s t cs ct,
    sigma_map s = Some cs ->
    sigma_map t = Some ct ->
    s = firstn (length s) t ->
    cs = firstn (length s) ct.
Proof.
  intros s t cs ct Hs Ht Hprefix.
  destruct (sigma_map_cases s Hs) as [[Hs1 Hcs] | [Hs2 Hcs]];
  destruct (sigma_map_cases t Ht) as [[Ht1 Hct] | [Ht2 Hct]];
  subst s; subst t; subst cs; subst ct; simpl in *;
  try discriminate; reflexivity.
Qed.

