Record TruthStatus : Type := {
  true_part : Prop;
  false_part : Prop
}.

Record LPModel (Const : Type) : Type := {
  lp_carrier : Type;
  lp_inhabitant : lp_carrier;
  lp_const : Const -> lp_carrier;
  lp_zero : lp_carrier;
  lp_succ : lp_carrier -> lp_carrier;
  lp_plus : lp_carrier -> lp_carrier -> lp_carrier;
  lp_times : lp_carrier -> lp_carrier -> lp_carrier;
  lp_positive : PredicateSymbol -> list lp_carrier -> Prop;
  lp_negative : PredicateSymbol -> list lp_carrier -> Prop
}.

Definition assignment {Const : Type} (M : LPModel Const) : Type :=
  nat -> lp_carrier M.

Definition update {A : Type} (g : nat -> A) (x : nat) (a : A) : nat -> A :=
  fun y => if Nat.eq_dec y x then a else g y.

Fixpoint eval_term {Const : Type} (M : LPModel Const)
    (g : assignment M) (t : FOTerm Const) : lp_carrier M :=
  match t with
  | TVar x => g x
  | TConst c => lp_const M c
  | TZero => lp_zero M
  | TSucc u => lp_succ M (@eval_term Const M g u)
  | TPlus u v => lp_plus M (@eval_term Const M g u) (@eval_term Const M g v)
  | TTimes u v => lp_times M (@eval_term Const M g u) (@eval_term Const M g v)
  end.

Definition eval_terms {Const : Type} (M : LPModel Const)
    (g : assignment M) (ts : list (FOTerm Const)) : list (lp_carrier M) :=
  map (@eval_term Const M g) ts.

Fixpoint lp_eval {Const : Type} (M : LPModel Const)
    (g : assignment M) (phi : Formula Const) : TruthStatus :=
  match phi with
  | FAtom p ts =>
      {| true_part := lp_positive M p (@eval_terms Const M g ts);
         false_part := lp_negative M p (@eval_terms Const M g ts) |}
  | FNeg p =>
      {| true_part := false_part (@lp_eval Const M g p);
         false_part := true_part (@lp_eval Const M g p) |}
  | FAnd p q =>
      {| true_part := true_part (@lp_eval Const M g p) /\
                       true_part (@lp_eval Const M g q);
         false_part := false_part (@lp_eval Const M g p) \/
                        false_part (@lp_eval Const M g q) |}
  | FOr p q =>
      {| true_part := true_part (@lp_eval Const M g p) \/
                       true_part (@lp_eval Const M g q);
         false_part := false_part (@lp_eval Const M g p) /\
                        false_part (@lp_eval Const M g q) |}
  | FForall x p =>
      {| true_part := forall a, true_part (@lp_eval Const M (update g x a) p);
         false_part := exists a, false_part (@lp_eval Const M (update g x a) p) |}
  | FExists x p =>
      {| true_part := exists a, true_part (@lp_eval Const M (update g x a) p);
         false_part := forall a, false_part (@lp_eval Const M (update g x a) p) |}
  end.

Definition designated {Const : Type} (M : LPModel Const)
    (g : assignment M) (phi : Formula Const) : Prop :=
  true_part (@lp_eval Const M g phi).

Definition Theory (Const : Type) : Type := Formula Const -> Prop.

Definition lp_entails {Const : Type}
    (Gamma : Theory Const) (phi : Formula Const) : Prop :=
  forall (M : LPModel Const) (g : assignment M),
    (forall gamma, Gamma gamma -> @designated Const M g gamma) ->
    @designated Const M g phi.

