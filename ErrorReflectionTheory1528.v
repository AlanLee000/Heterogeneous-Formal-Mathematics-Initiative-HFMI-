Definition correct_path (B : BottomEnvironment) (p : list (Correct B)) : Prop :=
  adjacent (correct_step B) p.

Definition ordinary_error_path
    (B : BottomEnvironment) (p : list (Error B)) : Prop :=
  adjacent (ordinary_error_step B) p.

Definition diff_set (A : ComparisonCalculus)
    (k : Dimension A) (c : Correct (base A)) (e : Error (base A))
    : Witness A -> Prop :=
  fun w => Diff A k c e w.

Definition next_set (A : ComparisonCalculus)
    (k : Dimension A) (c : Correct (base A)) (e : Error (base A))
    : Correct (base A) * Error (base A) -> Prop :=
  fun ce => Next A k c e (fst ce) (snd ce).

Definition back_set (A : ComparisonCalculus)
    (k : Dimension A) (c : Correct (base A)) (e : Error (base A))
    : Boundary (base A) * Rule (base A) -> Prop :=
  fun br => Back A k c e (fst br) (snd br).

(** Sections 4--5: object-language judgments and comparison-node terms. *)

Inductive ObjAtom (A : ComparisonCalculus) : Type :=
| DiffAt : Dimension A -> Correct (base A) -> Error (base A) ->
           Witness A -> ObjAtom A
| CmpAt : Dimension A -> Correct (base A) -> Error (base A) -> ObjAtom A.

Arguments DiffAt {A} _ _ _ _.
Arguments CmpAt {A} _ _ _.

Inductive obj_derives (A : ComparisonCalculus) : ObjAtom A -> Prop :=
| ObjCmpIntro : forall k c e w,
    Diff A k c e w ->
    @obj_derives A (CmpAt k c e).

Theorem obj_cmp_iff_has_diff :
  forall (A : ComparisonCalculus) k c e,
    @obj_derives A (CmpAt k c e) <->
    exists w, Diff A k c e w.
Proof.
  intros A k c e.
  split.
  - intros H.
    inversion H as [k' c' e' w Hdiff].
    exists w.
    exact Hdiff.
  - intros [w Hdiff].
    econstructor.
    exact Hdiff.
Qed.

Record CNode (A : ComparisonCalculus) : Type := mkCNode {
  node_correct : Correct (base A);
  node_error : Error (base A);
  node_dimension : Dimension A;
  node_witness : Witness A
}.

Arguments mkCNode {A} _ _ _ _.

Definition cnode_valid (A : ComparisonCalculus) (x : CNode A) : Prop :=
  Diff A (node_dimension x) (node_correct x) (node_error x)
         (node_witness x) /\
  InvDelta A (node_dimension x) (node_correct x) (node_error x)
             (node_witness x).

Lemma valid_node_yields_object_comparison :
  forall (A : ComparisonCalculus) (x : CNode A),
    @cnode_valid A x ->
    @obj_derives A
      (CmpAt (node_dimension x) (node_correct x) (node_error x)).
Proof.
  intros A x [Hdiff _].
  econstructor.
    exact Hdiff.
Qed.


(** Sections 6--7: partial path selectors and legal comparison paths. *)

Record PathSelector (A : ComparisonCalculus) : Type := {
  select_path : list (Error (base A)) -> option (list (Correct (base A)));
  select_only_nonempty : forall s cs,
      select_path s = Some cs -> s <> [];
  select_length : forall s cs,
      select_path s = Some cs -> length cs = length s;
  select_correct : forall s cs,
      select_path s = Some cs -> correct_path (base A) cs;
  select_prefix_closed : forall s cs m,
      select_path s = Some cs ->
      1 <= m <= length s ->
      exists cs', select_path (firstn m s) = Some cs';
  select_prefix_compatible : forall s t cs ct,
      select_path s = Some cs ->
      select_path t = Some ct ->
      s = firstn (length s) t ->
      cs = firstn (length s) ct
}.

Definition ErrSeq {A : ComparisonCalculus} (P : list (CNode A))
    : list (Error (base A)) :=
  map (@node_error A) P.

Definition CorrSeq {A : ComparisonCalculus} (P : list (CNode A))
    : list (Correct (base A)) :=
  map (@node_correct A) P.

Definition DimSeq {A : ComparisonCalculus} (P : list (CNode A))
    : list (Dimension A) :=
  map (@node_dimension A) P.

(** Equality of dimension sequences is equality in the presented quotient,
    pointwise, rather than Rocq's syntactic equality of representatives. *)
Definition quotient_dimseq_equiv {A : ComparisonCalculus}
    (P Q : list (CNode A)) : Prop :=
  Forall2 (dimension_equiv A) (DimSeq P) (DimSeq Q).

Definition WitSeq {A : ComparisonCalculus} (P : list (CNode A))
    : list (Witness A) :=
  map (@node_witness A) P.

Definition node_next {A : ComparisonCalculus} (x y : CNode A) : Prop :=
  Next A (node_dimension x) (node_correct x) (node_error x)
         (node_correct y) (node_error y).

Definition node_pres_delta {A : ComparisonCalculus}
    (x y : CNode A) : Prop :=
  PresDelta A (node_dimension x) (node_dimension y)
    (node_correct x) (node_error x) (node_witness x)
    (node_correct y) (node_error y) (node_witness y).

Definition legal_path {A : ComparisonCalculus}
    (sigma : PathSelector A) (P : list (CNode A)) : Prop :=
  P <> [] /\
  select_path sigma (ErrSeq P) = Some (CorrSeq P) /\
  Forall (@cnode_valid A) P /\
  adjacent node_next P /\
  adjacent node_pres_delta P.

Definition LPath {A : ComparisonCalculus}
    (sigma : PathSelector A) (n : nat) : list (CNode A) -> Prop :=
  fun P => length P = n /\ legal_path sigma P.

Lemma legal_path_selected_correct :
  forall (A : ComparisonCalculus) (sigma : PathSelector A) P,
    legal_path sigma P ->
    correct_path (base A) (CorrSeq P).
Proof.
  intros A sigma P [_ [Hselect _]].
  exact (select_correct sigma (ErrSeq P) Hselect).
Qed.

Lemma legal_path_selected_length :
  forall (A : ComparisonCalculus) (sigma : PathSelector A) P,
    legal_path sigma P ->
    length (CorrSeq P) = length (ErrSeq P).
Proof.
  intros A sigma P [_ [Hselect _]].
  exact (select_length sigma (ErrSeq P) Hselect).
Qed.

(** Section 8: continuation, failed attempts, and the terminal noise layer. *)

Fixpoint last_opt {A : Type} (xs : list A) : option A :=
  match xs with
  | [] => None
  | x :: [] => Some x
  | _ :: xs' => last_opt xs'
  end.

Definition can_continue {A : ComparisonCalculus}
    (sigma : PathSelector A) (P : list (CNode A))
    (cstar : Correct (base A)) (estar : Error (base A))
    (lambda : Dimension A) : Prop :=
  exists wstar,
    legal_path sigma (P ++ [mkCNode cstar estar lambda wstar]).

Definition fail_attempt {A : ComparisonCalculus}
    (sigma : PathSelector A) (P : list (CNode A))
    (cstar : Correct (base A)) (estar : Error (base A))
    (lambda : Dimension A) : Prop :=
  exists previous,
    last_opt P = Some previous /\
    Next A (node_dimension previous)
      (node_correct previous) (node_error previous) cstar estar /\
    select_path sigma (ErrSeq P ++ [estar]) =
      Some (CorrSeq P ++ [cstar]) /\
    ~ can_continue sigma P cstar estar lambda.

Definition extension_witness {A : ComparisonCalculus}
    (P : list (CNode A))
    (cstar : Correct (base A)) (estar : Error (base A))
    (lambda : Dimension A) (wstar : Witness A) : Prop :=
  exists previous,
    last_opt P = Some previous /\
    Diff A lambda cstar estar wstar /\
    InvDelta A lambda cstar estar wstar /\
    PresDelta A (node_dimension previous) lambda
      (node_correct previous) (node_error previous) (node_witness previous)
      cstar estar wstar.

(** [reason] is intentionally partial.  The source gives no value when a
    difference witness also satisfies the invariant and preservation test. *)
Definition reason {A : ComparisonCalculus}
    (sigma : PathSelector A) (P : list (CNode A))
    (cstar : Correct (base A)) (estar : Error (base A))
    (lambda : Dimension A) : option nat :=
  if excluded_middle_informative
       (exists wstar, Diff A lambda cstar estar wstar)
  then
    if excluded_middle_informative
         (exists wstar, extension_witness P cstar estar lambda wstar)
    then None
    else Some 1
  else Some 0.

Lemma reason_zero_iff_no_diff :
  forall (A : ComparisonCalculus) (sigma : PathSelector A)
         P cstar estar lambda,
    reason sigma P cstar estar lambda = Some 0 <->
    forall w, ~ Diff A lambda cstar estar w.
Proof.
  intros A sigma P cstar estar lambda.
  unfold reason.
  destruct (excluded_middle_informative
    (exists wstar, Diff A lambda cstar estar wstar)) as [Hex | Hnone].
  - destruct (excluded_middle_informative
      (exists wstar, extension_witness P cstar estar lambda wstar)).
    + split.
      * discriminate.
      * intros Hall.
        destruct Hex as [w Hw].
        exact (False_rect _ (Hall w Hw)).
    + split.
      * discriminate.
      * intros Hall.
        destruct Hex as [w Hw].
        exact (False_rect _ (Hall w Hw)).
  - split.
    + intros _ w Hw.
      apply Hnone.
      exists w.
      exact Hw.
    + intros _.
      reflexivity.
Qed.

Lemma reason_one_iff_diff_but_no_valid_extension_witness :
  forall (A : ComparisonCalculus) (sigma : PathSelector A)
         P cstar estar lambda,
    reason sigma P cstar estar lambda = Some 1 <->
    (exists w, Diff A lambda cstar estar w) /\
    ~ (exists w, extension_witness P cstar estar lambda w).
Proof.
  intros A sigma P cstar estar lambda.
  unfold reason.
  destruct (excluded_middle_informative
    (exists wstar, Diff A lambda cstar estar wstar)) as [Hex | Hnone].
  - destruct (excluded_middle_informative
      (exists wstar, extension_witness P cstar estar lambda wstar))
      as [Hext | Hnoext].
    + split.
      * discriminate.
      * intros [_ Hcontra].
        exact (False_rect _ (Hcontra Hext)).
    + split.
      * intros _.
        split; assumption.
      * intros _.
        reflexivity.
  - split.
    + discriminate.
    + intros [Hex _].
      exact (False_rect _ (Hnone Hex)).
Qed.

Lemma adjacent_snoc :
  forall (T : Type) (R : T -> T -> Prop)
         (xs : list T) last x,
    xs <> [] ->
    last_opt xs = Some last ->
    adjacent R xs ->
    R last x ->
    adjacent R (xs ++ [x]).
Proof.
  intros T R xs.
  induction xs as [| a xs IH].
  - intros last x Hnonempty.
    contradiction.
  - intros last x Hnonempty Hlast Hadj Hstep.
    destruct xs as [| b tail].
    + simpl in Hlast.
      inversion Hlast.
      subst last.
      simpl.
      split.
      * exact Hstep.
      * exact I.
    + change (last_opt (b :: tail) = Some last) in Hlast.
      change (R a b /\ adjacent R (b :: tail)) in Hadj.
      change (R a b /\ adjacent R ((b :: tail) ++ [x])).
      destruct Hadj as [Hab Htail].
      split.
      * exact Hab.
      * apply (IH last x).
        -- discriminate.
        -- exact Hlast.
        -- exact Htail.
        -- exact Hstep.
Qed.

Lemma extension_witness_yields_can_continue :
  forall (A : ComparisonCalculus) (sigma : PathSelector A)
         P cstar estar lambda,
    legal_path sigma P ->
    fail_attempt sigma P cstar estar lambda ->
    (exists w, extension_witness P cstar estar lambda w) ->
    can_continue sigma P cstar estar lambda.
Proof.
  intros A sigma P cstar estar lambda Hlegal Hfail Hext.
  destruct Hlegal as [Hnonempty [Hselected [Hnodes [Hnext Hpres]]]].
  destruct Hfail as [previous
    [Hlast [Hnextstar [Hselectedstar Hcannot]]]].
  destruct Hext as [w [previous'
    [Hlast' [Hdiff [Hinv Hpresstar]]]]].
  assert (Hprevious : previous = previous') by congruence.
  subst previous'.
  unfold can_continue.
  exists w.
  split.
  - intros Hnil.
    apply app_eq_nil in Hnil.
    destruct Hnil as [HP _].
    exact (Hnonempty HP).
  - split.
    + unfold ErrSeq, CorrSeq in *.
      rewrite !map_app.
      simpl.
      exact Hselectedstar.
    + split.
      * apply Forall_app.
        split.
        -- exact Hnodes.
        -- constructor.
           ++ split; assumption.
           ++ constructor.
      * split.
        -- eapply adjacent_snoc.
           ++ exact Hnonempty.
           ++ exact Hlast.
           ++ exact Hnext.
           ++ exact Hnextstar.
        -- eapply adjacent_snoc.
           ++ exact Hnonempty.
           ++ exact Hlast.
           ++ exact Hpres.
           ++ exact Hpresstar.
Qed.

Theorem failed_attempt_reason_is_defined :
  forall (A : ComparisonCalculus) (sigma : PathSelector A)
         P cstar estar lambda,
    legal_path sigma P ->
    fail_attempt sigma P cstar estar lambda ->
    exists q, reason sigma P cstar estar lambda = Some q.
Proof.
  intros A sigma P cstar estar lambda Hlegal Hfail.
  unfold reason.
  destruct (excluded_middle_informative
    (exists wstar, Diff A lambda cstar estar wstar)) as [Hex | Hnone].
  - destruct (excluded_middle_informative
      (exists wstar, extension_witness P cstar estar lambda wstar))
      as [Hext | Hnoext].
    + exfalso.
      destruct Hfail as [previous
        [Hlast [Hnextstar [Hselectedstar Hcannot]]]].
      apply Hcannot.
      eapply extension_witness_yields_can_continue.
      * exact Hlegal.
      * exists previous.
        repeat split; assumption.
      * exact Hext.
    + exists 1.
      reflexivity.
  - exists 0.
    reflexivity.
Qed.

(** The displayed source record has eight components including its Noise tag;
    the prose calling it a seven-tuple is corrected here. The constructor is
    the tag and the following seven fields are its payload. *)
Record NoiseRecord (A : ComparisonCalculus) : Type := mkNoiseRecord {
  noise_prefix : list (CNode A);
  noise_correct : Correct (base A);
  noise_error : Error (base A);
  noise_dimension : Dimension A;
  noise_error_sequence : list (Error (base A));
  noise_correct_sequence : list (Correct (base A));
  noise_reason : nat
}.

Arguments mkNoiseRecord {A} _ _ _ _ _ _ _.

Definition canonical_noise_record {A : ComparisonCalculus}
    (sigma : PathSelector A) (P : list (CNode A))
    (cstar : Correct (base A)) (estar : Error (base A))
    (lambda : Dimension A) : option (NoiseRecord A) :=
  match reason sigma P cstar estar lambda with
  | Some q =>
      Some (mkNoiseRecord P cstar estar lambda
        (ErrSeq P ++ [estar]) (CorrSeq P ++ [cstar]) q)
  | None => None
  end.

Definition valid_noise_record {A : ComparisonCalculus}
    (sigma : PathSelector A) (nu : NoiseRecord A) : Prop :=
  legal_path sigma (noise_prefix nu) /\
  fail_attempt sigma (noise_prefix nu)
    (noise_correct nu) (noise_error nu) (noise_dimension nu) /\
  noise_error_sequence nu = ErrSeq (noise_prefix nu) ++ [noise_error nu] /\
  noise_correct_sequence nu = CorrSeq (noise_prefix nu) ++ [noise_correct nu] /\
  reason sigma (noise_prefix nu)
    (noise_correct nu) (noise_error nu) (noise_dimension nu) =
    Some (noise_reason nu).
Inductive PathObject (A : ComparisonCalculus) : Type :=
| LegalObject : list (CNode A) -> PathObject A
| NoiseObject : NoiseRecord A -> PathObject A.

Arguments LegalObject {A} _.
Arguments NoiseObject {A} _.

Definition valid_object {A : ComparisonCalculus}
    (sigma : PathSelector A) (X : PathObject A) : Prop :=
  match X with
  | LegalObject P => legal_path sigma P
  | NoiseObject nu => valid_noise_record sigma nu
  end.

