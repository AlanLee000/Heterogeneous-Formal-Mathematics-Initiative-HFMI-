  repeat split.
  - exact (@I_Diff A U (certified_object CX) i node Hnth).
  - exact (@I_Cmp A U (certified_object CX) i node Hnth).
  - exact (@I_InvD A U (certified_object CX) i node Hnth).
  - exact (Hdiff i node Hnth).
  - exact (Hinv i node Hnth).
  - exact (Hcmp i node Hnth).
Qed.

