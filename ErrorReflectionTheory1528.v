(** Section 9: filtered local backtracking and path-level backtracking. *)

Definition BackInterface (A : ComparisonCalculus) : Type :=
  (Boundary (base A) * Rule (base A))%type.

Definition local_back {A : ComparisonCalculus}
    (x : CNode A) (br : BackInterface A) : Prop :=
  Back A (node_dimension x) (node_correct x) (node_error x)
       (fst br) (snd br) /\
  InvBack A (node_dimension x) (node_correct x) (node_error x)
    (node_witness x) (fst br) (snd br).

Fixpoint all_local_back {A : ComparisonCalculus}
    (P : list (CNode A)) (rho : list (BackInterface A)) : Prop :=
  match P, rho with
  | [], [] => True
  | x :: P', br :: rho' => local_back x br /\ all_local_back P' rho'
  | _, _ => False
  end.

Definition back_pres_step {A : ComparisonCalculus}
    (x : CNode A) (br : BackInterface A)
    (y : CNode A) (br' : BackInterface A) : Prop :=
  PresBack A (node_dimension x) (node_dimension y)
    (node_correct x) (node_error x) (node_witness x) (fst br) (snd br)
    (node_correct y) (node_error y) (node_witness y) (fst br') (snd br').

Fixpoint back_preserved_from {A : ComparisonCalculus}
    (x : CNode A) (br : BackInterface A)
    (P : list (CNode A)) (rho : list (BackInterface A)) : Prop :=
  match P, rho with
  | [], [] => True
  | y :: P', br' :: rho' =>
      back_pres_step x br y br' /\ back_preserved_from y br' P' rho'
  | _, _ => False
  end.

Definition back_preserved {A : ComparisonCalculus}
    (P : list (CNode A)) (rho : list (BackInterface A)) : Prop :=
  match P, rho with
  | [], [] => True
  | x :: P', br :: rho' => back_preserved_from x br P' rho'
  | _, _ => False
  end.

Definition BackTrace {A : ComparisonCalculus}
    (P : list (CNode A)) (rho : list (BackInterface A)) : Prop :=
  length rho = length P /\
  all_local_back P rho /\
  back_preserved P rho.

Fixpoint fold_dimensions {A : ComparisonCalculus}
    (acc : Dimension A) (ks : list (Dimension A)) : Dimension A :=
  match ks with
  | [] => acc
  | k :: ks' => fold_dimensions (dim_sequence A acc k) ks'
  end.

Definition DimFold {A : ComparisonCalculus}
    (P : list (CNode A)) : option (Dimension A) :=
  match DimSeq P with
  | [] => None
  | k :: ks => Some (fold_dimensions k ks)
  end.

Definition PathBackElement (A : ComparisonCalculus) : Type :=
  (Dimension A * list (BackInterface A))%type.

Definition PathBack {A : ComparisonCalculus}
    (P : list (CNode A)) : PathBackElement A -> Prop :=
  fun z =>
    exists d rho,
      z = (d, rho) /\
      DimFold P = Some d /\
      BackTrace P rho.

Definition HistBack {A : ComparisonCalculus}
    (X : PathObject A) : PathBackElement A -> Prop :=
  match X with
  | LegalObject P => PathBack P
  | NoiseObject nu => PathBack (noise_prefix nu)
  end.

Definition CurrentBack {A : ComparisonCalculus}
    (X : PathObject A) : PathBackElement A -> Prop :=
  match X with
  | LegalObject P => PathBack P
  | NoiseObject _ => fun _ => False
  end.

Lemma noise_preserves_history_but_permits_no_backtracking :
  forall (A : ComparisonCalculus) (nu : NoiseRecord A),
    (forall z, HistBack (NoiseObject nu) z <-> PathBack (noise_prefix nu) z) /\
    (forall z, ~ CurrentBack (NoiseObject nu) z).
Proof.
  intros A nu.
  split.
  - intros z.
    split.
    + intros H.
      exact H.
    + intros H.
      exact H.
  - intros z H.
    exact H.
Qed.

