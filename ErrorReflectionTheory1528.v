  forall (A : ComparisonCalculus) (sigma : PathSelector A)
         (U : UniversalMachine) (CX : @CertifiedPathObject A sigma)
         i node,
    nth_error (object_prefix (certified_object CX)) i = Some node ->
    @FailureTheory A U (certified_object CX)
