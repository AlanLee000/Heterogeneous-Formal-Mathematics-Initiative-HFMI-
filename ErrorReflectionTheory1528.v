(** This certificate is the mechanism carried by the reflected formulas:
    every recorded node comes from an actual Diff/InvDelta comparison, and
    every recorded adjacent pair comes from actual Next/PresDelta data. *)
Record ReflectionProvenance {A : ComparisonCalculus}
    (sigma : PathSelector A) (X : PathObject A) : Prop := {
  reflected_node_diff : forall i node,
    nth_error (object_prefix X) i = Some node ->
    Diff A (node_dimension node) (node_correct node) (node_error node)
      (node_witness node);
  reflected_node_invariant : forall i node,
    nth_error (object_prefix X) i = Some node ->
    InvDelta A (node_dimension node) (node_correct node) (node_error node)
      (node_witness node);
  reflected_node_comparison : forall i node,
    nth_error (object_prefix X) i = Some node ->
    @obj_derives A
      (CmpAt (node_dimension node) (node_correct node) (node_error node));
  reflected_step_next : forall i node next_node,
    nth_error (object_prefix X) i = Some node ->
    nth_error (object_prefix X) (S i) = Some next_node ->
    node_next node next_node;
  reflected_step_pres_delta : forall i node next_node,
    nth_error (object_prefix X) i = Some node ->
    nth_error (object_prefix X) (S i) = Some next_node ->
    node_pres_delta node next_node
}.

Theorem valid_object_has_reflection_provenance :
  forall (A : ComparisonCalculus) (sigma : PathSelector A)
         (X : PathObject A),
    valid_object sigma X ->
    ReflectionProvenance sigma X.
Proof.
  intros A sigma X Hvalid.
  pose proof (@valid_object_prefix_is_legal A sigma X Hvalid) as Hlegal.
  destruct Hlegal as [_ [_ [Hnodes [Hnext Hpres]]]].
  constructor.
  - intros i node Hnth.
    destruct (@forall_nth_error (CNode A) (@cnode_valid A)
      (object_prefix X) i node Hnodes Hnth) as [Hdiff Hinv].
    exact Hdiff.
  - intros i node Hnth.
    destruct (@forall_nth_error (CNode A) (@cnode_valid A)
      (object_prefix X) i node Hnodes Hnth) as [Hdiff Hinv].
    exact Hinv.
  - intros i node Hnth.
    apply valid_node_yields_object_comparison.
    exact (@forall_nth_error (CNode A) (@cnode_valid A)
      (object_prefix X) i node Hnodes Hnth).
  - intros i node next_node Hnth Hnextnth.
    eapply adjacent_nth_error; eauto.
  - intros i node next_node Hnth Hnextnth.
    eapply adjacent_nth_error; eauto.
Qed.

Inductive InFailureLanguage {A : ComparisonCalculus}
    (X : PathObject A) : FailureConst A -> Prop :=
| LangPath : InFailureLanguage X (FCPath X)
| LangNodeCorrect : forall i node,
    nth_error (object_prefix X) i = Some node ->
    InFailureLanguage X (FCNodeCorrect i (node_correct node))
| LangNodeError : forall i node,
    nth_error (object_prefix X) i = Some node ->
    InFailureLanguage X (FCNodeError i (node_error node))
| LangNodeDimension : forall i node,
    nth_error (object_prefix X) i = Some node ->
    InFailureLanguage X (FCNodeDimension i (node_dimension node))
| LangNodeWitness : forall i node,
    nth_error (object_prefix X) i = Some node ->
    InFailureLanguage X (FCNodeWitness i (node_witness node))
| LangFoldDimension : forall d rho,
    (HistBack X (d, rho) \/ CurrentBack X (d, rho)) ->
    InFailureLanguage X (FCFoldDimension d)
| LangTrace : forall d rho,
    (HistBack X (d, rho) \/ CurrentBack X (d, rho)) ->
    InFailureLanguage X (FCBackTrace rho)
| LangBackBoundary : forall d rho i br,
    (HistBack X (d, rho) \/ CurrentBack X (d, rho)) ->
    nth_error rho i = Some br ->
    InFailureLanguage X (FCBackBoundary (fst br))
| LangBackRule : forall d rho i br,
    (HistBack X (d, rho) \/ CurrentBack X (d, rho)) ->
    nth_error rho i = Some br ->
    InFailureLanguage X (FCBackRule (snd br))
| LangStarCorrect : forall nu,
    X = NoiseObject nu ->
    InFailureLanguage X (FCStarCorrect (noise_correct nu))
| LangStarError : forall nu,
    X = NoiseObject nu ->
    InFailureLanguage X (FCStarError (noise_error nu))
| LangStarDimension : forall nu,
    X = NoiseObject nu ->
    InFailureLanguage X (FCStarDimension (noise_dimension nu))
| LangNoiseReason : forall nu,
    X = NoiseObject nu ->
    InFailureLanguage X (FCNoiseReason (noise_reason nu)).

(** The object-indexed language as an actual subtype carrier.  The predicate
    [InFailureLanguage] is its characteristic membership relation. *)
Definition DynamicFailureLanguage {A : ComparisonCalculus}
    (X : PathObject A) : Type :=
  { c : FailureConst A | InFailureLanguage X c }.

Fixpoint term_in_failure_language {A : ComparisonCalculus}
    (X : PathObject A) (t : FOTerm (FailureConst A)) : Prop :=
  match t with
  | TVar _ | TZero => True
  | TConst c => InFailureLanguage X c
  | TSucc u => term_in_failure_language X u
  | TPlus u v | TTimes u v =>
      term_in_failure_language X u /\ term_in_failure_language X v
  end.

Fixpoint formula_in_failure_language {A : ComparisonCalculus}
    (X : PathObject A) (phi : Formula (FailureConst A)) : Prop :=
  match phi with
  | FAtom _ ts => Forall (term_in_failure_language X) ts
  | FNeg p => formula_in_failure_language X p
  | FAnd p q | FOr p q =>
      formula_in_failure_language X p /\ formula_in_failure_language X q
  | FForall _ p | FExists _ p => formula_in_failure_language X p
  end.

Definition tx {A : ComparisonCalculus} (X : PathObject A)
    : FOTerm (FailureConst A) := TConst (FCPath X).
Definition tcorr {A : ComparisonCalculus} (i : nat) (x : CNode A)
    : FOTerm (FailureConst A) := TConst (FCNodeCorrect i (node_correct x)).
Definition terr {A : ComparisonCalculus} (i : nat) (x : CNode A)
    : FOTerm (FailureConst A) := TConst (FCNodeError i (node_error x)).
Definition tdim {A : ComparisonCalculus} (i : nat) (x : CNode A)
    : FOTerm (FailureConst A) :=
  TConst (FCNodeDimension i (node_dimension x)).
Definition twit {A : ComparisonCalculus} (i : nat) (x : CNode A)
    : FOTerm (FailureConst A) :=
  TConst (FCNodeWitness i (node_witness x)).

Definition conflict_formula {A : ComparisonCalculus} (X : PathObject A)
    : Formula (FailureConst A) :=
  FAtom PConflict [tx X].

Inductive FailureTheory (A : ComparisonCalculus) (U : UniversalMachine)
    (X : PathObject A) : Theory (FailureConst A) :=
| I_TC : forall phi,
    @TC (FailureConst A) U phi ->
    @FailureTheory A U X phi
| I_Conflict :
    @FailureTheory A U X (conflict_formula X)
| I_NotConflict :
    @FailureTheory A U X (FNeg (conflict_formula X))
| I_CorrectNode : forall i node,
    nth_error (object_prefix X) i = Some node ->
    @FailureTheory A U X
      (FAtom PCorrectNode [tcorr i node])
| I_ErrorNode : forall i node,
    nth_error (object_prefix X) i = Some node ->
    @FailureTheory A U X
      (FAtom PErrorNode [terr i node])
| I_Dimension : forall i node,
    nth_error (object_prefix X) i = Some node ->
    @FailureTheory A U X
      (FAtom PDimension [tdim i node])
| I_Witness : forall i node,
    nth_error (object_prefix X) i = Some node ->
    @FailureTheory A U X
      (FAtom PWitness [twit i node])
| I_Diff : forall i node,
    nth_error (object_prefix X) i = Some node ->
    @FailureTheory A U X
      (FAtom PDiff [tdim i node; tcorr i node; terr i node; twit i node])
| I_Cmp : forall i node,
    nth_error (object_prefix X) i = Some node ->
    @FailureTheory A U X
      (FAtom PCmp [tdim i node; tcorr i node; terr i node])
| I_InvD : forall i node,
    nth_error (object_prefix X) i = Some node ->
    @FailureTheory A U X
      (FAtom PInvD [tdim i node; tcorr i node; terr i node; twit i node])
| I_ReflectNode : forall i node,
    nth_error (object_prefix X) i = Some node ->
    @FailureTheory A U X
      (FAtom PReflectNode
        [tx X; numeral i; tcorr i node; terr i node; tdim i node; twit i node])
| I_ReflectCmp : forall i node,
    nth_error (object_prefix X) i = Some node ->
    @FailureTheory A U X
      (FAtom PReflectCmp
        [tx X; numeral i; tdim i node; tcorr i node; terr i node; twit i node])
| I_ProofReflects : forall i node,
    nth_error (object_prefix X) i = Some node ->
    @FailureTheory A U X
      (FAtom PProofReflects [tx X; numeral i])
| I_NextPair : forall i node next_node,
    nth_error (object_prefix X) i = Some node ->
    nth_error (object_prefix X) (S i) = Some next_node ->
    @FailureTheory A U X
      (FAtom PNextPair
        [tx X; numeral i; tdim i node; tcorr i node; terr i node;
         tcorr (S i) next_node; terr (S i) next_node])
| I_PresD : forall i node next_node,
    nth_error (object_prefix X) i = Some node ->
    nth_error (object_prefix X) (S i) = Some next_node ->
    @FailureTheory A U X
      (FAtom PPresD
        [tdim i node; tdim (S i) next_node;
         tcorr i node; terr i node; twit i node;
         tcorr (S i) next_node; terr (S i) next_node;
         twit (S i) next_node])
| I_ReflectStep : forall i node next_node,
    nth_error (object_prefix X) i = Some node ->
    nth_error (object_prefix X) (S i) = Some next_node ->
    @FailureTheory A U X
      (FAtom PReflectStep
        [tx X; numeral i; tdim i node; tcorr i node; terr i node;
         tcorr (S i) next_node; terr (S i) next_node])
| I_RawErrorAt : forall i node,
    nth_error (object_prefix X) i = Some node ->
    @FailureTheory A U X
      (FAtom PRawErrorAt [tx X; numeral i; terr i node])
| I_SelectedCorrectAt : forall i node,
    nth_error (object_prefix X) i = Some node ->
    @FailureTheory A U X
      (FAtom PSelectedCorrectAt [tx X; numeral i; tcorr i node])
| I_BackTrace : forall P d rho,
    X = LegalObject P ->
    PathBack P (d, rho) ->
    @FailureTheory A U X
      (FAtom PBackTrace
        [tx X; TConst (FCBackTrace rho); TConst (FCFoldDimension d)])
| I_BackInterface : forall P d rho i node br,
    X = LegalObject P ->
    PathBack P (d, rho) ->
    nth_error P i = Some node ->
    nth_error rho i = Some br ->
    @FailureTheory A U X
      (FAtom PBackInterface
        [tx X; numeral i; tdim i node; tcorr i node; terr i node;
         TConst (FCBackBoundary (fst br));
         TConst (FCBackRule (snd br))])
| I_PriorBackTrace : forall nu d rho,
    X = NoiseObject nu ->
    PathBack (noise_prefix nu) (d, rho) ->
    @FailureTheory A U X
      (FAtom PPriorBackTrace
        [tx X; TConst (FCBackTrace rho); TConst (FCFoldDimension d)])
| I_PriorBackInterface : forall nu d rho i node br,
    X = NoiseObject nu ->
    PathBack (noise_prefix nu) (d, rho) ->
    nth_error (noise_prefix nu) i = Some node ->
    nth_error rho i = Some br ->
    @FailureTheory A U X
      (FAtom PPriorBackInterface
        [tx X; numeral i; tdim i node; tcorr i node; terr i node;
         TConst (FCBackBoundary (fst br));
         TConst (FCBackRule (snd br))])
| I_NoiseRecord : forall nu,
    X = NoiseObject nu ->
    @FailureTheory A U X
      (FAtom PNoiseRecord
        [tx X; numeral (length (noise_prefix nu));
         TConst (FCStarDimension (noise_dimension nu));
         TConst (FCStarCorrect (noise_correct nu));
         TConst (FCStarError (noise_error nu));
         TConst (FCNoiseReason (noise_reason nu))])
| I_AttemptedCmp : forall nu,
    X = NoiseObject nu ->
    @FailureTheory A U X
      (FAtom PAttemptedCmp
        [tx X; numeral (length (noise_prefix nu));
         TConst (FCStarDimension (noise_dimension nu));
         TConst (FCStarCorrect (noise_correct nu));
         TConst (FCStarError (noise_error nu))])
| I_NoiseRawError : forall nu,
    X = NoiseObject nu ->
    @FailureTheory A U X
      (FAtom PRawErrorAt
        [tx X; numeral (length (noise_prefix nu));
         TConst (FCStarError (noise_error nu))])
| I_NoiseSelectedCorrect : forall nu,
    X = NoiseObject nu ->
    @FailureTheory A U X
      (FAtom PSelectedCorrectAt
        [tx X; numeral (length (noise_prefix nu));
         TConst (FCStarCorrect (noise_correct nu))])
| I_NoDiffReason : forall nu,
    X = NoiseObject nu ->
    noise_reason nu = 0 ->
    @FailureTheory A U X
      (FForall 0
        (FNeg (FAtom PDiff
          [TConst (FCStarDimension (noise_dimension nu));
           TConst (FCStarCorrect (noise_correct nu));
           TConst (FCStarError (noise_error nu));
           TVar 0])))
| I_ReasonOne : forall nu,
    X = NoiseObject nu ->
    noise_reason nu = 1 ->
    @FailureTheory A U X
      (FAtom PNoiseRecord
        [tx X; numeral (length (noise_prefix nu));
         TConst (FCStarDimension (noise_dimension nu));
         TConst (FCStarCorrect (noise_correct nu));
         TConst (FCStarError (noise_error nu));
