  forall x y z, f x y -> f x z -> y = z.

Record UniversalMachine : Type := {
  UTM : nat -> nat -> nat -> nat -> Prop;
  PartialRecursive : (nat -> nat -> Prop) -> Prop;
  partial_recursive_is_function : forall f,
      PartialRecursive f -> PartialFunction f;
  universal_program : forall f,
      PartialRecursive f ->
      exists p, forall x y,
        f x y <-> exists t, UTM p x t y
}.

Definition u_atom {Const : Type} (p x t y : nat) : Formula Const :=
  FAtom PU [numeral p; numeral x; numeral t; numeral y].

Definition TC {Const : Type} (U : UniversalMachine) : Theory Const :=
  fun phi =>
    exists p x t y,
      UTM U p x t y /\
      phi = u_atom p x t y.

Definition halts_formula {Const : Type} (p x y : nat) : Formula Const :=
  FExists 0
    (FAtom PU [numeral p; numeral x; TVar 0; numeral y]).


Lemma halts_witness_designated :
  forall (Const : Type) (M : LPModel Const)
         (g : assignment M) p x t y,
    @designated Const M g (@u_atom Const p x t y) ->
    @designated Const M
      (update g 0 (@eval_term Const M g (numeral t)))
      (FAtom PU [numeral p; numeral x; TVar 0; numeral y]).
Proof.
  intros Const M g p x t y H.
  change (lp_positive M PU
    [@eval_term Const M g (numeral p);
     @eval_term Const M g (numeral x);
     @eval_term Const M g (numeral t);
     @eval_term Const M g (numeral y)]) in H.
  change (lp_positive M PU
    [@eval_term Const M
       (update g 0 (@eval_term Const M g (numeral t))) (numeral p);
     @eval_term Const M
       (update g 0 (@eval_term Const M g (numeral t))) (numeral x);
     @eval_term Const M g (numeral t);
     @eval_term Const M
       (update g 0 (@eval_term Const M g (numeral t))) (numeral y)]).
  rewrite (@eval_numeral_assignment_irrelevant
    Const M (update g 0 (@eval_term Const M g (numeral t))) g p).
  rewrite (@eval_numeral_assignment_irrelevant
    Const M (update g 0 (@eval_term Const M g (numeral t))) g x).
  rewrite (@eval_numeral_assignment_irrelevant
    Const M (update g 0 (@eval_term Const M g (numeral t))) g y).
  exact H.
Qed.
