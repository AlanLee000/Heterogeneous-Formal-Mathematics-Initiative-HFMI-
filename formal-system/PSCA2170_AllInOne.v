Record token := Token { token_id : nat; token_body : token_payload }.

Definition persistent_payload (p : token_payload) : Prop :=
  match p with
  | CertTokP _ | CxTokP _ _ | ModelTokP _ _ _ => True
  | _ => False
  end.

Definition persistent_payloadb (p : token_payload) : bool :=
  match p with
  | CertTokP _ | CxTokP _ _ | ModelTokP _ _ _ => true
  | _ => false
  end.

Lemma persistent_payloadb_spec : forall p,
  persistent_payloadb p = true <-> persistent_payload p.
Proof.
  intro p.
