Fixpoint parity_count (G : generator_data) (odd : bool) (F : list nat) : nat :=
  match F with
  | [] => 0
  | t :: ts =>
      (if Bool.eqb (Nat.odd (nu_g G t)) odd then 1 else 0) +
      parity_count G odd ts
  end.

Definition Prof2 (G : generator_data) (c : forest_certificate) : nat * nat :=
  (parity_count G false (cert_forest c),
   parity_count G true (cert_forest c)).

Definition Gate2 (G : generator_data) (c : forest_certificate) : Prop :=
  fst (Prof2 G c) = snd (Prof2 G c) /\ 0 < fst (Prof2 G c).

Definition SemCert (G : generator_data) (c : forest_certificate) : Prop :=
  V G c = true /\ Gate2 G c.

Lemma Forall2_right_witness :
  forall (A B : Type) (R : A -> B -> Prop) xs ys y,
    Forall2 R xs ys -> In y ys ->
    exists x, In x xs /\ R x y.
Proof.
  intros A B R xs ys y H.
  induction H as [|x y0 xs ys Hxy Hrest IH].
  - intros Hin. contradiction.
  - intros [Heq | Hin].
    + subst y0. exists x. split.
      * left. reflexivity.
      * exact Hxy.
    + destruct (IH Hin) as [x' [Hinx' HR]].
      exists x'. split.
      * right. exact Hinx'.
      * exact HR.
Qed.

Theorem verified_forest_is_exact :
  forall G c t, V G c = true ->
    ((exists r, comp_run_g G (cert_word c) r t) <->
     In t (cert_forest c)).
Proof.
  intros G c t HV.
  apply (verifier_spec G c) in HV.
  destruct HV as [_ [_ [_ [Hruns Hcover]]]].
  split.
  - intros [r Hrun].
    eapply coverage_sound.
    + exact Hcover.
    + exact Hrun.
  - intro Hin.
    destruct (@Forall2_right_witness nat nat (comp_run_g G (cert_word c)) (cert_runs c) (cert_forest c) t Hruns Hin) as [r [_ Hrun]].
    exists r.
    exact Hrun.
Qed.

