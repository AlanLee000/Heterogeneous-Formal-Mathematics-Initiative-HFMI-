(*
  Explicit interface for the standard acceptable program numbering fixed in
  source section 2.  It contains only the usual closure/undecidability
  metatheory used in section 13; it is not an axiom in the executable PSCA
  kernel or finite model.
*)
Record effective_metatheory : Type := EffectiveMetatheory {
  em_phi : nat -> nat -> nat -> Prop;
  em_RE1 : (nat -> Prop) -> Prop;
  em_RE2 : (nat -> nat -> Prop) -> Prop;
  em_Recursive1 : (nat -> nat) -> Prop;
  em_Recursive2 : (nat -> nat -> nat) -> Prop;

  em_RE2_ext : forall P Q,
    (forall x y, P x y <-> Q x y) -> em_RE2 P -> em_RE2 Q;
  em_halt_RE : em_RE2 (fun e x => exists v, em_phi e x v);
  em_RE_preimage2 : forall R f g,
    em_RE2 R -> em_Recursive2 f -> em_Recursive2 g ->
    em_RE2 (fun x y => R (f x y) (g x y));
  em_RE_projection : forall R,
    em_RE2 R -> em_RE1 (fun y => exists x, R x y);
  em_RE1_preimage2 : forall P f,
    em_RE1 P -> em_Recursive2 f ->
    em_RE2 (fun x y => P (f x y));

  em_recursive_comp11 : forall f g,
    em_Recursive1 f -> em_Recursive1 g ->
    em_Recursive1 (fun x => f (g x));
  em_recursive_pair : forall f g h,
    em_Recursive2 f -> em_Recursive1 g -> em_Recursive1 h ->
    em_Recursive2 (fun x y => f (g x) (h y));
  em_recursive_left : forall f,
    em_Recursive1 f -> em_Recursive2 (fun x _ => f x);
  em_const_recursive : forall n,
    em_Recursive1 (fun _ => n);

  em_RE_both_sides_decidable : forall P,
    em_RE2 P -> em_RE2 (fun x y => ~ P x y) ->
    forall x y, {P x y} + {~ P x y};
  em_halting_undecidable :
    (forall e x, {exists v, em_phi e x v} +
                 {~ exists v, em_phi e x v}) -> False;

  em_nowhere : nat;
  em_nowhere_spec : forall x v, ~ em_phi em_nowhere x v;
  em_specialize : nat -> nat -> nat;
  em_specialize_recursive : em_Recursive2 em_specialize;
  em_specialize_zero : forall e x,
    (forall u v,
      em_phi (em_specialize e x) u v <-> em_phi em_nowhere u v) <->
    ~ exists v, em_phi e x v
}.

Definition program_equiv (E : effective_metatheory) (e f : nat) : Prop :=
  forall x v, em_phi E e x v <-> em_phi E f x v.

Theorem program_equivalence_is_not_RE :
  forall E, ~ em_RE2 E (program_equiv E).
Proof.
  intros E HequivRE.
  assert (Hconst1 : em_Recursive1 E (fun _ => em_nowhere E)).
  - apply em_const_recursive.
  - assert (Hconst2 : em_Recursive2 E (fun _ _ => em_nowhere E)).
    + apply em_recursive_left.
      exact Hconst1.
    + pose proof (em_RE_preimage2 E
        (program_equiv E) (em_specialize E)
        (fun _ _ => em_nowhere E)
        HequivRE (em_specialize_recursive E) Hconst2) as Hpre.
      assert (Hnonhalt :
        em_RE2 E (fun e x => ~ exists v, em_phi E e x v)).
      * eapply em_RE2_ext.
        -- intros e x.
           apply em_specialize_zero.
        -- exact Hpre.
      * apply (em_halting_undecidable E).
        apply (em_RE_both_sides_decidable E
          (fun e x => exists v, em_phi E e x v)).
        -- exact (em_halt_RE E).
        -- exact Hnonhalt.
Qed.

(*
  All finite tuples below are represented by their fixed natural-number code.
  Thus every displayed higher-arity source constructor becomes a binary
  function (formula code, tuple-payload code), without losing a coordinate.
*)
Record static_target (E : effective_metatheory) : Type := StaticTarget {
  st_formb : nat -> bool;
  st_event_formula : nat -> nat -> nat;
  st_pcomp_formula : nat -> nat -> nat;
  st_state_rel_formula : nat -> nat -> nat;
  st_attach_formula : nat -> nat -> nat;
  st_source_inc_formula : nat -> nat -> nat;
  st_fill_formula : nat -> nat -> nat;
  st_curv_formula : nat -> nat -> nat;
  st_state_form_formula : nat -> nat -> nat;
  st_qcomp_formula : nat -> nat -> nat;
  st_eq_formula : nat -> nat -> nat;

  st_form_recursive : em_Recursive1 E (fun n => if st_formb n then 1 else 0);
  st_event_recursive : em_Recursive2 E st_event_formula;
  st_pcomp_recursive : em_Recursive2 E st_pcomp_formula;
  st_state_rel_recursive : em_Recursive2 E st_state_rel_formula;
  st_attach_recursive : em_Recursive2 E st_attach_formula;
  st_source_inc_recursive : em_Recursive2 E st_source_inc_formula;
  st_fill_recursive : em_Recursive2 E st_fill_formula;
  st_curv_recursive : em_Recursive2 E st_curv_formula;
  st_state_form_recursive : em_Recursive2 E st_state_form_formula;
  st_qcomp_recursive : em_Recursive2 E st_qcomp_formula;
  st_eq_recursive : em_Recursive2 E st_eq_formula;

  (* Conservative totalization: on every well-formed leading formula, each
     constructor returns a formula even for natural payloads outside the
     intended typed coding domain.  Hence the source typing laws hold on the
     intended domain without introducing partial operations. *)
  st_event_closed : forall A z,
      st_formb A = true -> st_formb (st_event_formula A z) = true;
  st_pcomp_closed : forall A z,
      st_formb A = true -> st_formb (st_pcomp_formula A z) = true;
  st_state_rel_closed : forall A z,
      st_formb A = true -> st_formb (st_state_rel_formula A z) = true;
  st_attach_closed : forall A z,
      st_formb A = true -> st_formb (st_attach_formula A z) = true;
  st_source_inc_closed : forall A z,
      st_formb A = true -> st_formb (st_source_inc_formula A z) = true;
  st_fill_closed : forall A z,
      st_formb A = true -> st_formb (st_fill_formula A z) = true;
  st_curv_closed : forall A z,
      st_formb A = true -> st_formb (st_curv_formula A z) = true;
  st_state_form_closed : forall A z,
      st_formb A = true -> st_formb (st_state_form_formula A z) = true;
  st_qcomp_closed : forall A z,
      st_formb A = true -> st_formb (st_qcomp_formula A z) = true;
  st_eq_closed : forall A B,
      st_formb A = true -> st_formb B = true ->
      st_formb (st_eq_formula A B) = true;

  st_prf : nat -> nat -> Prop;
  st_prf_RE : em_RE2 E st_prf;
  st_prf_wf : forall pi A, st_prf pi A -> st_formb A = true
}.

Definition target_provable {E} (L : static_target E) (A : nat) : Prop :=
  exists pi, st_prf L pi A.

Record source_public_signature (E : effective_metatheory) : Type :=
  SourcePublicSignature {
    sp_event : nat -> nat -> Prop;
    sp_pcomp : nat -> nat -> Prop;
    sp_state_rel : nat -> nat -> Prop;
    sp_attach : nat -> nat -> Prop;
    sp_source_inc : nat -> nat -> Prop;
    sp_fill : nat -> nat -> Prop;
    sp_curv : nat -> nat -> Prop;
    sp_state_form : nat -> nat -> Prop;
    sp_qcomp : nat -> nat -> Prop;
    sp_obseq : nat -> nat -> Prop;
    sp_J : nat -> nat;
    sp_J_recursive : em_Recursive1 E sp_J;
    sp_J_characterizes_programs : forall e f,
      sp_obseq (sp_J e) (sp_J f) <-> program_equiv E e f
  }.

Record qualified_encoding (E : effective_metatheory)
    (S : source_public_signature E) (L : static_target E) : Type :=
  QualifiedEncoding {
    qe_assembly : nat -> nat;
    qe_state : nat -> nat;
    qe_assembly_recursive : em_Recursive1 E qe_assembly;
    qe_state_recursive : em_Recursive1 E qe_state;

    qe_event_iff : forall a ev,
      sp_event S a ev <->
      target_provable L (st_event_formula L (qe_assembly a) ev);
    qe_pcomp_iff : forall triple payload,
      sp_pcomp S triple payload <->
      target_provable L (st_pcomp_formula L (qe_assembly triple) payload);
    qe_state_rel_iff : forall s payload,
      sp_state_rel S s payload <->
      target_provable L (st_state_rel_formula L (qe_state s) payload);
    qe_attach_iff : forall s payload,
      sp_attach S s payload <->
      target_provable L (st_attach_formula L (qe_state s) payload);
    qe_source_inc_iff : forall s payload,
      sp_source_inc S s payload <->
      target_provable L (st_source_inc_formula L (qe_state s) payload);
    qe_fill_iff : forall s payload,
      sp_fill S s payload <->
      target_provable L (st_fill_formula L (qe_state s) payload);
    qe_curv_iff : forall s payload,
      sp_curv S s payload <->
      target_provable L (st_curv_formula L (qe_state s) payload);
    qe_state_form_iff : forall s payload,
      sp_state_form S s payload <->
      target_provable L (st_state_form_formula L (qe_state s) payload);
    qe_qcomp_iff : forall s payload,
      sp_qcomp S s payload <->
      target_provable L (st_qcomp_formula L (qe_state s) payload);

    qe_full_abstraction : forall a b,
      sp_obseq S a b <->
      target_provable L
        (st_eq_formula L (qe_assembly a) (qe_assembly b))
  }.

Definition J_query {E S L}
    (Q : @qualified_encoding E S L) (e f : nat) : nat :=
  st_eq_formula L
    (qe_assembly Q (sp_J S e))
    (qe_assembly Q (sp_J S f)).

Lemma J_query_recursive :
  forall E S L (Q : @qualified_encoding E S L),
    em_Recursive2 E (J_query Q).
Proof.
  intros E S L Q.
  unfold J_query.
  apply em_recursive_pair.
  - exact (st_eq_recursive L).
  - apply em_recursive_comp11.
    + exact (qe_assembly_recursive Q).
    + exact (sp_J_recursive S).
  - apply em_recursive_comp11.
    + exact (qe_assembly_recursive Q).
    + exact (sp_J_recursive S).
Qed.

Theorem theorem_13_1_no_effective_fully_abstract_encoding :
  forall E (S : source_public_signature E) (L : static_target E),
    @qualified_encoding E S L -> False.
Proof.
  intros E S L Q.
  apply (program_equivalence_is_not_RE E).
  assert (Hprov : em_RE1 E (target_provable L)).
  - apply em_RE_projection.
    exact (st_prf_RE L).
  - assert (Hqueries :
      em_RE2 E (fun e f => target_provable L (J_query Q e f))).
    + apply em_RE1_preimage2.
      * exact Hprov.
      * apply J_query_recursive.
    + eapply em_RE2_ext.
      * intros e f.
        unfold J_query.
        rewrite <- (qe_full_abstraction Q (sp_J S e) (sp_J S f)).
        apply sp_J_characterizes_programs.
      * exact Hqueries.
Qed.

(*
  Section 14 package.  A packaged kernel must carry a transition witness
  indexed by that very kernel; an unrelated prototype model is not enough.
*)
Record KernelTransitionModel (P : psca_kernel) : Type := {
  transition_source : context;
  transition_operation : op;
  transition_target : context;
  transition_trace : list token;
  transition_rule :
    Rule P transition_source transition_operation
      transition_target transition_trace;
  transition_nonidentity : transition_source <> transition_target
}.

Record PSCA_2_3 : Type := PSCA23 {
  system_kernel : psca_kernel;
  system_rule : context -> op -> context -> list token -> Prop;
  system_rule_exact : system_rule = Rule system_kernel;
  system_derivation :
    context -> list (op * list token) -> context -> Prop;
  system_derivation_exact : system_derivation = Der system_kernel;
  system_event : assembly system_kernel -> event -> Prop;
  system_event_exact : system_event = event_holds;
  system_transition_model : KernelTransitionModel system_kernel
}.

Definition package_PSCA_2_3
    (P : psca_kernel) (M : KernelTransitionModel P) : PSCA_2_3 :=
  {| system_kernel := P;
     system_rule := Rule P;
     system_rule_exact := eq_refl;
     system_derivation := Der P;
     system_derivation_exact := eq_refl;
     system_event := event_holds;
     system_event_exact := eq_refl;
     system_transition_model := M |}.

Definition string_has_semantics (P : psca_kernel) (w : word) : Prop :=
  exists c M K G0 G1 tr,
    cert_word c = w /\ SemCert (pk_generator P) c /\ pk_qual P c M /\
    pk_initial P c = Some K /\ Der P G0 tr G1 /\
    exists A : assembly P,
      asm_certificate A = c /\ asm_model A = M.


