Inductive Rule (P : psca_kernel) :
    context -> op -> context -> list token -> Prop :=
| Rule_VERIFY : forall G G' c raw certtok cxtok K0,
    In raw (ctx_linear G) -> token_body raw = RawCertP c ->
    SemCert (pk_generator P) c -> pk_initial P c = Some K0 ->
    token_body certtok = CertTokP c -> token_body cxtok = CxTokP c K0 ->
    context_update G G' [raw] [] [certtok; cxtok] ->
    Rule P G VERIFY G' [certtok; cxtok]
| Rule_ADMIT : forall G G' c K M certtok cxtok modeltok,
    In certtok (ctx_persistent G) -> token_body certtok = CertTokP c ->
    In cxtok (ctx_persistent G) -> token_body cxtok = CxTokP c K ->
    pk_qual P c M -> token_body modeltok = ModelTokP c M K ->
    context_update G G' [] [certtok; cxtok] [modeltok] ->
    Rule P G ADMIT_MODEL G' [modeltok]
| Rule_ISSUE : forall G G' c K n nonce p h cxtok pathtok,
    In cxtok (ctx_persistent G) -> token_body cxtok = CxTokP c K ->
    In nonce (ctx_linear G) -> token_body nonce = NonceP n ->
    pk_path_ok P c p -> h = pk_state_eta P c K (pk_path_chain P c p) ->
    token_body pathtok = PathTokP c K p h n ->
    context_update G G' [nonce] [cxtok] [pathtok] ->
    Rule P G ISSUE_PATH G' [pathtok]
| Rule_PLACE : forall G G' c M K t x n modeltok nonce insttok,
    In modeltok (ctx_persistent G) ->
    token_body modeltok = ModelTokP c M K ->
    pk_instance P c M K t x ->
    In nonce (ctx_linear G) -> token_body nonce = NonceP n ->
    token_body insttok = InstTokP c M K t x n ->
    context_update G G' [nonce] [modeltok] [insttok] ->
    Rule P G PLACE G' [insttok]
| Rule_ASSEMBLE : forall G G' c M K t x nx p h np modeltok pathtok insttok
      sigma e y outinst seedtok,
    In modeltok (ctx_persistent G) ->
    token_body modeltok = ModelTokP c M K ->
    In pathtok (ctx_linear G) ->
    token_body pathtok = PathTokP c K p h np ->
    In insttok (ctx_linear G) ->
    token_body insttok = InstTokP c M K t x nx ->
    path_start p = t -> pk_transport P c M K p x = Some y ->
    sc_kind K sigma = Some Slot -> sc_active K sigma = Some true ->
    pk_first_nonbottom P (pk_source_word P p) = sc_color K sigma ->
    token_body outinst = InstTokP c M K (path_finish p) y nx ->
    token_body seedtok = SeedTokP c M K sigma p h e np ->
    context_update G G' [pathtok; insttok] [modeltok] [outinst; seedtok] ->
    Rule P G ASSEMBLE G' [outinst; seedtok]
| Rule_MATERIALIZE : forall G G' c M K sigma p h e n K'
      seed cxtok modeltok newcx newmodel attach,
    In seed (ctx_linear G) ->
    token_body seed = SeedTokP c M K sigma p h e n ->
    closed_path p -> pk_attach P c K sigma p = Some K' ->
    In cxtok (ctx_persistent G) -> token_body cxtok = CxTokP c K ->
    In modeltok (ctx_persistent G) ->
    token_body modeltok = ModelTokP c M K ->
    token_body newcx = CxTokP c K' ->
    token_body newmodel = ModelTokP c M K' ->
    token_body attach = AttachTokP c K sigma p K' ->
    context_update G G' [seed] [cxtok; modeltok] [newcx; newmodel; attach] ->
    Rule P G MATERIALIZE G' [newcx; newmodel; attach]
| Rule_PROVE_REL : forall G G' c K n v w nonce cxtok reltok,
    In cxtok (ctx_persistent G) -> token_body cxtok = CxTokP c K ->
    In nonce (ctx_linear G) -> token_body nonce = NonceP n ->
    pk_relation_witness P c K v w ->
    token_body reltok = RelTokP c K v w ->
    context_update G G' [nonce] [cxtok] [reltok] ->
    Rule P G PROVE_REL G' [reltok]
| Rule_COMPARE_FILL : forall G G' c M K s p hp ep np t q hq eq nq
      seedp seedq phi filltok,
    In seedp (ctx_linear G) ->
    token_body seedp = SeedTokP c M K s p hp ep np ->
    In seedq (ctx_linear G) ->
    token_body seedq = SeedTokP c M K t q hq eq nq ->
    pk_square_ready P K s p t q ->
    pk_compare P K s p t q = inl phi ->
    token_body filltok = FillTokP c K s p t q phi ->
    context_update G G' [seedp; seedq] [] [filltok] ->
    Rule P G COMPARE_ORDER G' [filltok]
| Rule_COMPARE_CURV : forall G G' c M K s p hp ep np t q hq eq nq
      seedp seedq kappa d curvtok,
    In seedp (ctx_linear G) ->
    token_body seedp = SeedTokP c M K s p hp ep np ->
    In seedq (ctx_linear G) ->
    token_body seedq = SeedTokP c M K t q hq eq nq ->
    pk_square_ready P K s p t q ->
    pk_compare P K s p t q = inr (kappa, d) ->
    token_body curvtok = CurvTokP c K s p t q kappa d ->
    context_update G G' [seedp; seedq] [] [curvtok] ->
    Rule P G COMPARE_ORDER G' [curvtok]
| Rule_FORM : forall G G' c K u n cxtok nonce formtok ruletok,
    In cxtok (ctx_persistent G) -> token_body cxtok = CxTokP c K ->
    In nonce (ctx_linear G) -> token_body nonce = NonceP n ->
    pk_form P K u -> token_body formtok = FormTokP c K u ->
    token_body ruletok = RuleSeedTokP c K u n ->
    context_update G G' [nonce] [cxtok] [formtok; ruletok] ->
    Rule P G FORM_OP G' [formtok; ruletok]
| Rule_FEEDBACK_FORM : forall G G' c K u n ruletok outtok,
    In ruletok (ctx_linear G) ->
    token_body ruletok = RuleSeedTokP c K u n ->
    token_body outtok = OutTokP (pk_seed P u n) ->
    context_update G G' [ruletok] [] [outtok] ->
    Rule P G FEEDBACK_FORM G' [outtok]
| Rule_FEEDBACK_TRACE : forall G G' c M K s p h e n seed u r v outtok,
    In seed (ctx_linear G) ->
    token_body seed = SeedTokP c M K s p h e n ->
    trace_g (pk_generator P) e u r v ->
    token_body outtok = OutTokP
      (emit_g (pk_generator P)
        (cantor_pair (cert_cover_proof c) (sc_root K)) (cantor_pair u v)) ->
    context_update G G' [seed] [] [outtok] ->
    Rule P G FEEDBACK_TRACE G' [outtok]
| Rule_BOUNDARY : forall G G' c M K s p h e n seed u q newseed boundary,
    In seed (ctx_linear G) ->
    token_body seed = SeedTokP c M K s p h e n ->
    prefix_trace_g (pk_generator P) e u q ->
    token_body newseed = SeedTokP c M K s p h e n ->
    token_body boundary = BoundaryTokP e u q ->
    context_update G G' [seed] [] [newseed; boundary] ->
    Rule P G BOUNDARY_PREFIX G' [newseed; boundary].

