Definition canonical_event_extensionality (P : psca_kernel) : Prop :=
  forall A B : assembly P,
    (forall i k s a r act,
      event_holds A (SiteEv i k s a r act) <->
      event_holds B (SiteEv i k s a r act)) ->
    (forall j i h w,
      event_holds A (CellEv j i h w) <->
      event_holds B (CellEv j i h w)) ->
    (forall i j,
      event_holds A (BirthEv i j) <->
      event_holds B (BirthEv i j)) ->
    asm_complex A = asm_complex B.

Lemma kernel_canonical_event_extensionality :
  forall P, canonical_event_extensionality P.
Proof.
  intros P A B Hsite Hcell Hbirth.
  apply (pk_canonical_fields_extensional P).
  - exact (asm_canonical A).
  - exact (asm_canonical B).
  - intros i k s a r act. exact (Hsite i k s a r act).
  - intros j i h w. exact (Hcell j i h w).
  - intros i j. exact (Hbirth i j).
Qed.
Lemma observation_implies_beta :
  forall P (A B : assembly P),
    same_interface A B -> canonical_event_extensionality P ->
    ObsEq A B -> beta_equal A B.
Proof.
  intros P A B Hif Hcanonical Hobs.
  destruct Hif as [Hc [Hm [Ht [Ht' [Hx [Hs Hp]]]]]].
  assert (HK : asm_complex A = asm_complex B).
  - apply Hcanonical.
    + intros. apply Hobs.
    + intros. apply Hobs.
    + intros. apply Hobs.
  - constructor.
    + exact HK.
    + specialize (Hobs (NowEv (asm_target_point A)
        (Nat.modulo (nu_g (pk_generator P) (asm_target_tree A)) 2))).
      apply (proj1 Hobs).
      split.
      * reflexivity.
      * reflexivity.
    + intro v. exact (Hobs (AttachRelEv v)).
    + intros u v. exact (Hobs (HaltOutEv u v)).
Qed.

Lemma beta_implies_observation :
  forall P (A B : assembly P),
    same_interface A B -> beta_equal A B -> ObsEq A B.
Proof.
  intros P A B Hif Hbeta ev.
  destruct Hif as [Hc [Hm [Ht [Ht' [Hx [Hs Hp]]]]]].
  destruct Hbeta as [HK Hnow Hnext Hprog].
  destruct ev; cbn.
  - now rewrite Hc, Hm.
  - now rewrite Hc, HK.
  - rewrite Hnow, Ht'. tauto.
  - apply Hnext.
  - now rewrite HK.
  - now rewrite HK.
  - now rewrite HK.
  - now rewrite HK.
  - now rewrite HK.
  - now rewrite HK.
  - apply Hprog.
Qed.

Theorem observational_equivalence_iff_beta :
  forall P (A B : assembly P),
    same_interface A B ->
    (ObsEq A B <-> beta_equal A B).
Proof.
  intros P A B Hif.
  split.
  - apply observation_implies_beta.
    + exact Hif.
    + apply kernel_canonical_event_extensionality.
  - apply beta_implies_observation.
    exact Hif.
Qed.


