Record source_groupoid (O : Type) : Type := SourceGroupoid {
  sg_filler : O -> O -> nat -> Prop;
  sg_id_code : O -> nat;
  sg_id_filler : forall x, sg_filler x x (sg_id_code x);
  sg_inverse_code : nat -> nat;
  sg_inverse_filler : forall x y phi,
    sg_filler x y phi -> sg_filler y x (sg_inverse_code phi);
  sg_comp_code : nat -> nat -> nat;
  sg_comp_filler : forall x y z phi psi,
    sg_filler x y phi -> sg_filler y z psi ->
    sg_filler x z (sg_comp_code psi phi);
  sg_holonomy : O -> nat;
  sg_spectrum : O -> list (signed_source * nat);
  sg_future : O -> nat -> Prop;
  sg_filler_preserves_holonomy : forall x y phi,
    sg_filler x y phi -> sg_holonomy x = sg_holonomy y;
  sg_filler_preserves_spectrum : forall x y phi,
    sg_filler x y phi -> sg_spectrum x = sg_spectrum y;
  sg_filler_preserves_future : forall x y phi r,
    sg_filler x y phi -> (sg_future x r <-> sg_future y r)
}.

Definition reconstructed_groupoid {O} (G : source_groupoid O) :
    source_groupoid (reconstructed_object O).
Proof.
  refine {| sg_filler := fun x y phi =>
              sg_filler G (decode_reconstruction x)
                (decode_reconstruction y) phi;
            sg_id_code := fun x => sg_id_code G (decode_reconstruction x);
            sg_inverse_code := sg_inverse_code G;
            sg_comp_code := sg_comp_code G;
            sg_holonomy := fun x => sg_holonomy G (decode_reconstruction x);
            sg_spectrum := fun x => sg_spectrum G (decode_reconstruction x);
            sg_future := fun x => sg_future G (decode_reconstruction x) |}.
  - intro x. apply sg_id_filler.
  - intros x y phi H. apply sg_inverse_filler. exact H.
  - intros x y z phi psi Hphi Hpsi.
    eapply sg_comp_filler; eauto.
  - intros x y phi H. eapply sg_filler_preserves_holonomy; eauto.
  - intros x y phi H. eapply sg_filler_preserves_spectrum; eauto.
  - intros x y phi r H. eapply sg_filler_preserves_future; eauto.
Defined.

Record source_groupoid_iso {O O' : Type}
