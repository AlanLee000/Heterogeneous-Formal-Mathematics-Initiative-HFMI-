Theorem license_quotient_universal :
  forall P c D (f : nat -> D),
    respects_license_relation P c f <->
    unique_eta_factor P c f.
Proof.
  intros P c D f. split.
  - intro Hrespect.
    exists (fun a => f (pk_eta_rep P c a)).
    split.
    + intro x. apply Hrespect. apply pk_eta_section.
    + intros bar' Hbar' a.
      specialize (Hbar' (pk_eta_rep P c a)).
