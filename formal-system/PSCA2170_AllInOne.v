Definition incidence (K : source_complex) (x y : nat) : Prop :=
  (In x (sc_sites K) /\ In y (sc_cells K) /\
   sc_attachment K y = Some x) \/
  (In x (sc_cells K) /\ In y (sc_sites K) /\
   sc_birth K y = Some x).

Definition acyclic {A : Type} (R : A -> A -> Prop) : Prop :=
  forall x, ~ clos_trans A R x x.

