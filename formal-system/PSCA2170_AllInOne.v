Qed.

Record context := Context {
  ctx_history : list (nat * nat);
  ctx_persistent : list token;
  ctx_linear : list token
}.

Definition ids (xs : list token) : list nat := map token_id xs.

Definition ContextWF (G : context) : Prop :=
  NoDup (ids (ctx_persistent G ++ ctx_linear G)) /\
  (forall t, In t (ctx_persistent G) -> persistent_payload (token_body t)) /\
  (forall t, In t (ctx_linear G) -> ~ persistent_payload (token_body t)) /\
  (forall t, In t (ctx_persistent G) -> ~ In t (ctx_linear G)) /\
  acyclic (fun x y => In (x, y) (ctx_history G)).

Definition initial_context (G : context) : Prop :=
  ContextWF G /\ ctx_persistent G = [] /\
  exists c raw nonces,
    token_body raw = RawCertP c /\
    (forall t, In t nonces -> exists n, token_body t = NonceP n) /\
    ctx_linear G = raw :: nonces /\
    ctx_history G = [].

Definition same_members {A : Type} (xs ys : list A) : Prop :=
  forall x, In x xs <-> In x ys.

Definition parent_edges (inputs outputs : list token) : list (nat * nat) :=
  flat_map
    (fun i => map (fun o => (token_id i, token_id o)) outputs)
    inputs.

Definition context_update (G G' : context)
    (consumed read outputs : list token) : Prop :=
  ContextWF G /\ ContextWF G' /\
  (forall t, In t consumed -> In t (ctx_linear G)) /\
  (forall t, In t read -> In t (ctx_persistent G)) /\
  NoDup (ids outputs) /\
  (forall o, In o outputs ->
     ~ In (token_id o) (ids (ctx_persistent G ++ ctx_linear G))) /\
  same_members (ctx_persistent G')
    (ctx_persistent G ++ filter (fun t => persistent_payloadb (token_body t)) outputs) /\
  (forall t,
    In t (ctx_linear G') <->
      (In t (ctx_linear G) /\ ~ In t consumed) \/
      (In t outputs /\ ~ persistent_payload (token_body t))) /\
  same_members (ctx_history G')
    (ctx_history G ++ parent_edges (consumed ++ read) outputs).

Inductive op : Type :=
| VERIFY | ADMIT_MODEL | ISSUE_PATH | PLACE | ASSEMBLE | MATERIALIZE
| PROVE_REL | COMPARE_ORDER | FORM_OP | FEEDBACK_FORM
