(* A closed, nonempty execution fragment: verified certificate, shared
   model, and assembly of a seed. *)
Inductive proto_phase := RawPhase | VerifiedPhase | ModelPhase | SeedPhase.
Inductive proto_step : proto_phase -> proto_phase -> Prop :=
| ProtoVerify : proto_step RawPhase VerifiedPhase
| ProtoAdmitModel : proto_step VerifiedPhase ModelPhase
| ProtoAssemble : proto_step ModelPhase SeedPhase.

Inductive proto_derivation : proto_phase -> proto_phase -> Prop :=
| ProtoDer_refl : forall p, proto_derivation p p
| ProtoDer_cons : forall p q r,
    proto_derivation p q -> proto_step q r -> proto_derivation p r.

Lemma prototype_has_a_nonempty_legal_derivation :
  proto_derivation RawPhase SeedPhase.
Proof.
  eapply ProtoDer_cons.
  - eapply ProtoDer_cons.
    + eapply ProtoDer_cons.
      * apply ProtoDer_refl.
      * apply ProtoVerify.
    + apply ProtoAdmitModel.
  - apply ProtoAssemble.
Qed.

