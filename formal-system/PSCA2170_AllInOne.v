Section FlatNormalization.
  Context {State Base RuleName : Type}.
  Variable base_of : State -> Base.
  Variable state_form : State -> RuleName -> Prop.

  Record flat_normalization (Y : Type) : Type := FlatNormalization {
    flat_P : State -> Y;
    flat_Pbar : Base -> Y;
    flat_form : Y -> RuleName -> Prop;
    flat_factors : forall K, flat_P K = flat_Pbar (base_of K);
    flat_preserves_form : forall K r,
      state_form K r <-> flat_form (flat_P K) r
  }.

  Theorem equal_base_different_form_forbids_flat_normalization :
    forall K L r,
      base_of K = base_of L ->
      state_form K r -> ~ state_form L r ->
      forall (Y : Type), flat_normalization Y -> False.
  Proof.
    intros K L r Hbase HK HL Y FN.
    destruct FN as [P Pbar FY Hfactor Hform].
    apply HL.
    apply (proj2 (Hform L r)).
    rewrite Hfactor.
    rewrite <- Hbase.
    rewrite <- Hfactor.
    apply (proj1 (Hform K r)).
    exact HK.
  Qed.
End FlatNormalization.

