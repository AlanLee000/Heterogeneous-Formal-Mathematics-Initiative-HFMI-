Theorem PathEquiv_is_equivalence :
  forall P c, Equivalence (PathEquiv P c).
Proof.
  intros P c. constructor.
  - intro p. repeat split; reflexivity.
  - intros p q [Hs [Ht He]]. repeat split; symmetry; assumption.
  - intros p q r [Hs1 [Ht1 He1]] [Hs2 [Ht2 He2]].
    repeat split; congruence.
Qed.

