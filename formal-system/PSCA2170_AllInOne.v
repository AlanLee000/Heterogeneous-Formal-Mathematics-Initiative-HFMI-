Record source_signature (S : Type) : Type := SourceSignature {
  state_rel : S -> nat -> Prop;
  attach_edge : S -> nat -> raw_path -> S -> Prop;
  source_site_rel : S -> nat -> source_kind -> nat -> option nat -> nat -> bool -> Prop;
  source_cell_rel : S -> nat -> nat -> nat -> list signed_source -> Prop;
  birth_rel : S -> nat -> nat -> Prop;
  fill_sq_rel : S -> nat -> raw_path -> nat -> raw_path -> nat -> Prop;
  curv_sq_rel : S -> nat -> raw_path -> nat -> raw_path -> nat -> nat -> Prop;
  state_form_rel : S -> nat -> Prop;
  qcomp_rel : S -> S -> S -> Prop;
  omega_rel : S -> list (signed_source * nat) -> Prop;
  source_extensional : forall x y,
    (forall v, state_rel x v <-> state_rel y v) ->
    (forall i k c a f b,
      source_site_rel x i k c a f b <->
      source_site_rel y i k c a f b) ->
    (forall j i h w,
      source_cell_rel x j i h w <-> source_cell_rel y j i h w) ->
    (forall i j, birth_rel x i j <-> birth_rel y i j) ->
    x = y
}.

Record fully_faithful_state_translation
    {S T : Type} (SS : source_signature S) (TS : source_signature T) : Type :=
  FullyFaithfulStateTranslation {
    translate_state : S -> T;
    ff_state_rel : forall x v,
      state_rel SS x v <-> state_rel TS (translate_state x) v;
    ff_attach : forall x s p y,
      attach_edge SS x s p y <->
      attach_edge TS (translate_state x) s p (translate_state y);
    ff_site : forall x i k c a f b,
      source_site_rel SS x i k c a f b <->
      source_site_rel TS (translate_state x) i k c a f b;
    ff_cell : forall x j i h w,
      source_cell_rel SS x j i h w <->
      source_cell_rel TS (translate_state x) j i h w;
    ff_birth : forall x i j,
      birth_rel SS x i j <-> birth_rel TS (translate_state x) i j;
    ff_fill : forall x s p t q phi,
      fill_sq_rel SS x s p t q phi <->
      fill_sq_rel TS (translate_state x) s p t q phi;
    ff_curv : forall x s p t q k d,
      curv_sq_rel SS x s p t q k d <->
      curv_sq_rel TS (translate_state x) s p t q k d;
    ff_form : forall x r,
      state_form_rel SS x r <-> state_form_rel TS (translate_state x) r;
    ff_qcomp : forall x y z,
      qcomp_rel SS x y z <->
      qcomp_rel TS (translate_state x) (translate_state y) (translate_state z);
    ff_omega : forall x w,
      omega_rel SS x w <-> omega_rel TS (translate_state x) w
  }.

Theorem fully_faithful_translation_is_injective :
  forall S T (SS : source_signature S) (TS : source_signature T)
    (F : fully_faithful_state_translation SS TS) x y,
    translate_state F x = translate_state F y -> x = y.
Proof.
  intros S T SS TS F x y Heq.
  apply (source_extensional SS x y).
  - intro v.
    rewrite (ff_state_rel F x v), (ff_state_rel F y v), Heq.
    reflexivity.
  - intros i k c a f b.
    rewrite (ff_site F x i k c a f b), (ff_site F y i k c a f b), Heq.
    reflexivity.
  - intros j i h w.
    rewrite (ff_cell F x j i h w), (ff_cell F y j i h w), Heq.
    reflexivity.
  - intros i j.
    rewrite (ff_birth F x i j), (ff_birth F y i j), Heq.
    reflexivity.
Qed.

