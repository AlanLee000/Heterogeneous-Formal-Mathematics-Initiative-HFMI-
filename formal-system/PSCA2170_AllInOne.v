Inductive event : Type :=
| QualEv
| BaseRelEv (v : nat)
| NowEv (point parity : nat)
| AttachRelEv (v : nat)
| SiteEv (site : nat) (kind : source_kind) (color : nat)
    (anchor : option nat) (frame : nat) (active : bool)
| CellEv (cell site boundary : nat) (sources : list signed_source)
| BirthEv (site cell : nat)
| FormEv (rule : nat)
| FillEv (sigma : nat) (p : raw_path) (tau : nat) (q : raw_path)
| CurvEv (sigma : nat) (p : raw_path) (tau : nat) (q : raw_path)
    (kappa : nat)
| HaltOutEv (input output : nat).

Definition event_holds {P} (A : assembly P) (ev : event) : Prop :=
  match ev with
  | QualEv => pk_qual P (asm_certificate A) (asm_model A)
  | BaseRelEv v => pk_B P (asm_certificate A) (asm_complex A) v
  | NowEv b parity =>
      b = asm_target_point A /\
      parity = Nat.modulo (nu_g (pk_generator P) (asm_target_tree A)) 2
  | AttachRelEv v =>
      exists K', pk_attach P (asm_certificate A) (asm_complex A)
        (asm_slot A) (asm_path A) = Some K' /\
        pk_B P (asm_certificate A) K' v
  | SiteEv i k s a r act =>
      sc_kind (asm_complex A) i = Some k /\
      sc_color (asm_complex A) i = Some s /\
      sc_anchor (asm_complex A) i = a /\
      sc_frame (asm_complex A) i = Some r /\
      sc_active (asm_complex A) i = Some act
  | CellEv j i h w =>
      sc_attachment (asm_complex A) j = Some i /\
      sc_boundary (asm_complex A) j = Some h /\
      sc_source_word (asm_complex A) j = Some w
  | BirthEv i j => sc_birth (asm_complex A) i = Some j
  | FormEv r => pk_form P (asm_complex A) r
  | FillEv s p t q => pk_filler P (asm_complex A) s p t q
  | CurvEv s p t q k =>
      ~ pk_filler P (asm_complex A) s p t q /\
      k = pk_curv P (asm_complex A) p q
  | HaltOutEv u v => phi_g (pk_generator P) (asm_program A) u v
  end.

Definition ObsEq {P} (A B : assembly P) : Prop :=
  forall ev, event_holds A ev <-> event_holds B ev.

Definition PathCompEv {P} (A0 A1 A2 : assembly P) : Prop :=
