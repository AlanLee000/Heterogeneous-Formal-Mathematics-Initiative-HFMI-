Lemma finite_history_edge : forall x y,
  In (x, y) (parent_edges
    ([finite_nonce] ++ [finite_cx_token]) [finite_path_token]) ->
  y = 2 /\ (x = 1 \/ x = 0).
Proof.
  intros x y H. cbn in H.
  destruct H as [H | [H | []]]; inversion H; subst; auto.
Qed.

Lemma finite_history_path : forall x y,
  clos_trans nat
    (fun a b => In (a, b)
      (parent_edges ([finite_nonce] ++ [finite_cx_token]) [finite_path_token]))
    x y ->
  y = 2 /\ x <> 2.
Proof.
  intros x y H.
  induction H.
  - apply finite_history_edge in H.
    destruct H as [Hy [Hx | Hx]]; subst; split; congruence.
  - destruct IHclos_trans1 as [Hy Hx].
    destruct IHclos_trans2 as [_ Hyne].
    subst y. contradiction.
Qed.

Lemma finite_history_acyclic :
  acyclic (fun a b =>
    In (a, b)
      (parent_edges ([finite_nonce] ++ [finite_cx_token]) [finite_path_token])).
Proof.
  intros x H.
  apply finite_history_path in H.
  tauto.
Qed.

